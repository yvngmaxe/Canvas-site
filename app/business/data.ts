/** 修学旅行プログラムの登壇者の実名を出すか（智也さんの確認が取れたら true に） */
export const SHOW_SPEAKER_NAMES = true;

export type Meta = { label: string; value: string };
export type Tone = "accent" | "ink" | "sub" | "soft";

/** 「内容と流れ」の中身（事例ごとにパンフの図の形が違うので、形ごとに用意） */
export type FlowBlock =
  | { kind: "text"; text: string }
  | { kind: "note"; text: string }
  // 年間の流れ（キャリア探究講座）
  | {
      kind: "timeline";
      phases: { label: string; span: number; tone: Tone }[];
      steps: { when: string; label: string; strong?: boolean }[];
    }
  // 番号つきの項目を2列で（AIはてなラボの4分野）
  | { kind: "numberGrid"; items: { title: string; text: string; tone: Tone }[] }
  // 番号つきの縦の流れ（PSI の5ステップ）
  | { kind: "numberList"; items: { title: string; text: string }[] }
  // STEP1〜4 の問い（AIはてなラボ）
  | {
      kind: "questions";
      items: { step: string; label: string; question: string }[];
      note: string;
    }
  // 登壇者（修学旅行）
  | {
      kind: "people";
      heading: string;
      people: { name: string; role: string }[];
    }
  // 時間の帯＋3つの説明（修学旅行）
  | {
      kind: "schedule";
      bar: { label: string; minutes: number; tone: Tone }[];
      items: { title: string; text: string; tone: Tone }[];
    }
  // 2列（大和町・問いほぐし）
  | { kind: "twoCol"; cols: FlowCol[] };

export type FlowCol = {
  heading?: string;
  boxed?: boolean; // 白いカードで囲む（ほぐれた例）
  tagged?: { tag: string; text: string }[]; // 「発掘」「練り上げ」などのラベルつき
  paras?: string[];
  bullets?: string[];
  sub?: { heading: string; paras?: string[]; bullets?: string[] }[];
};

// 写真（パンフレットと同じ位置に入れる。素材は public/images/business/）
export type Photo = {
  src: StaticImageData;
  alt: string;
  /** 縦長の写真を横長に切るときに見せる位置（例 "center 35%"） */
  position?: string;
  /** ロゴは切らずに白い地に全体を見せる */
  logo?: boolean;
};

export type Case = {
  /** 事例のページのアドレス（/business/<柱>/<slug>） */
  slug: string;
  title: string;
  target?: string; // 「〇〇 向け」
  catchLead?: string; // キャッチの前の赤い一言（PSI の「遊び心 × 起業家精神」）
  catchCopy?: string;
  meta?: Meta[];
  subline?: string; // 見出しなしの太字1行（03 の事例：対象と日程）
  question?: string; // 問い
  // 詳しい中身（01・02 の事例）
  background?: string[];
  aimsIntro?: string;
  aimsNumbered?: boolean;
  aims?: { title: string; text?: string }[];
  flow?: FlowBlock[];
  ideas?: { title: string; text: string }[];
  ideasInline?: boolean; // 工夫の文章が長いときは「見出し＋本文」を横に続ける
  // 短い事例（03）
  body?: string[];
  points?: string[];
  // 写真：01・02 は名前の右に縦に並べる（pair＝1つの枠に左右2枚）。03 はカードの下に横に並べる
  photos?: Photo[];
  photoLayout?: "stack" | "pair";
};

// 自社のプロダクト（R&D）：柱のページにカード、/business/rnd/<slug> に説明ページ
export type Product = {
  slug: string;
  kicker: string; // 「自己探求AI」
  title: string;
  catchCopy: string;
  status?: string; // 「2027年3月ローンチ予定」
  logo: StaticImageData;
  /** 説明ページの途中に出す事例（ほかの柱の事例へのリンク） */
  relatedCases?: { pillarId: string; slug: string }[];
};

